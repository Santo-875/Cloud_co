def test_gemini_client_timeout(caplog) -> None:
    from unittest.mock import MagicMock, patch

    import httpx

    secret_key = "secret_key_timeout_xyz_999"
    with patch("httpx.Client") as mock_client_cls:
        mock_client = MagicMock()
        mock_client_cls.return_value.__enter__.return_value = mock_client
        mock_client.post.side_effect = httpx.TimeoutException(
            f"Connection to https://api.google.com?key={secret_key} timed out after 30.0s"
        )

        client = GeminiClient(api_key=secret_key)
        with pytest.raises(RuntimeError) as exc_info:
            client.complete("test prompt")

        err_msg = str(exc_info.value)
        assert secret_key not in err_msg
        assert "[REDACTED_API_KEY]" in err_msg
        assert secret_key not in caplog.text


