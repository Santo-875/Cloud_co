"""LLM Client interfaces, Gemini client, and MockLLMClient for offline testing."""

import os
from typing import Protocol

import httpx


class LLMClient(Protocol):
    """Protocol for LLM interactions."""

    def complete(self, prompt: str, system_prompt: str | None = None) -> str:
        """Synchronously return text completion."""
        ...


class MockLLMClient:
    """Offline, deterministic mock client for testing with zero network requests."""

    def __init__(self, responses: dict[str, str] | None = None) -> None:
        self.responses = responses or {}
        self.last_prompt: str | None = None
        self.last_system_prompt: str | None = None

    def complete(self, prompt: str, system_prompt: str | None = None) -> str:
        self.last_prompt = prompt
        self.last_system_prompt = system_prompt

        # Check for matching canned response or generate deterministic fallback
        for k, v in self.responses.items():
            if k.lower() in prompt.lower():
                return v

        if "explain_architecture" in prompt.lower() or "architecture" in prompt.lower():
            return "This cloud architecture contains standard VPC networking, compute, and data persistence layers."
        if "finding" in prompt.lower() or "security" in prompt.lower():
            return "Security assessment identified open SSH ingress and unencrypted storage risks requiring mitigation."

        return "Response generated by MockLLMClient based strictly on the provided context."


class GeminiClient:
    """Client for Google Gemini API reading GEMINI_API_KEY from environment."""

    def __init__(
        self,
        api_key: str | None = None,
        model: str = "gemini-1.5-flash",
        timeout: float = 30.0,
    ) -> None:
        # Strictly obtain key from environment or parameter, never hardcoded
        self.api_key = api_key or os.environ.get("GEMINI_API_KEY")
        self.model = model
        self.timeout = timeout

        if not self.api_key:
            raise ValueError(
                "GEMINI_API_KEY environment variable is not set. Cannot initialize GeminiClient."
            )

    def complete(self, prompt: str, system_prompt: str | None = None) -> str:
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model}:generateContent?key={self.api_key}"

        contents = []
        if system_prompt:
            contents.append(
                {
                    "role": "user",
                    "parts": [{"text": f"SYSTEM INSTRUCTION: {system_prompt}"}],
                }
            )
            contents.append(
                {
                    "role": "model",
                    "parts": [
                        {
                            "text": "Understood. I will strictly follow the instructions and answer only from the provided data."
                        }
                    ],
                }
            )

        contents.append({"role": "user", "parts": [{"text": prompt}]})
        payload = {"contents": contents}

        try:
            with httpx.Client(timeout=self.timeout) as client:
                resp = client.post(url, json=payload)
                resp.raise_for_status()
                data = resp.json()
                candidates = data.get("candidates", [])
                if candidates:
                    parts = candidates[0].get("content", {}).get("parts", [])
                    if parts:
                        return str(parts[0].get("text", ""))
                return "No text response generated by model."
        except httpx.HTTPError as exc:
            # Mask API key if it inadvertently appears in any URL exception
            err_msg = str(exc).replace(str(self.api_key), "[REDACTED_API_KEY]")
            raise RuntimeError(f"Gemini API request failed: {err_msg}") from None
